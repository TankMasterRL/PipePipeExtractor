package org.schabi.newpipe.mcp;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.modelcontextprotocol.json.McpJsonMapper;
import io.modelcontextprotocol.json.McpJsonMapperSupplier;
import org.junit.jupiter.api.Test;
import org.schabi.newpipe.extractor.MediaFormat;
import org.schabi.newpipe.extractor.stream.SubtitlesStream;

import java.util.List;
import java.util.Map;
import java.util.ServiceLoader;

/**
 * The {@code get_subtitles} result: caption track metadata plus where to get each track's text,
 * and the caption formats a caller may ask for.
 */
class SubtitlesTest {

    private static Serializer serializer() {
        final McpJsonMapper mapper = ServiceLoader.load(McpJsonMapperSupplier.class)
                .findFirst()
                .map(McpJsonMapperSupplier::get)
                .orElseThrow();
        return new Serializer(new Cursor(mapper));
    }

    private static SubtitlesStream track(final String language, final boolean autoGenerated,
                                         final String content, final boolean isUrl) {
        return new SubtitlesStream.Builder()
                .setContent(content, isUrl)
                .setMediaFormat(MediaFormat.VTT)
                .setLanguageCode(language)
                .setAutoGenerated(autoGenerated)
                .build();
    }

    @SuppressWarnings("unchecked")
    private static List<Map<String, Object>> items(final Map<String, Object> result) {
        return (List<Map<String, Object>>) result.get("items");
    }

    @Test
    void eachTrackCarriesItsLanguageKindFormatAndTextUrl() {
        final Map<String, Object> result = serializer().subtitles(0,
                "https://www.youtube.com/watch?v=aBcDeFgHiJk",
                List.of(track("ko", false, "https://example.com/timedtext?lang=ko&fmt=vtt", true),
                        track("ko", true, "https://example.com/timedtext?lang=ko&kind=asr", true)));

        assertEquals(0, result.get("serviceId"));
        assertEquals("https://www.youtube.com/watch?v=aBcDeFgHiJk", result.get("url"));
        final Map<String, Object> uploader = items(result).get(0);
        assertEquals("ko", uploader.get("languageTag"));
        assertEquals("한국어", uploader.get("languageName"));
        assertEquals(Boolean.FALSE, uploader.get("autoGenerated"));
        assertEquals("VTT", uploader.get("format"));
        assertEquals("https://example.com/timedtext?lang=ko&fmt=vtt", uploader.get("url"));
        assertFalse(uploader.containsKey("content"));
        assertEquals(Boolean.TRUE, items(result).get(1).get("autoGenerated"));
    }

    @Test
    void textTheExtractorRewroteIsReturnedInlineInsteadOfAUrl() {
        final Map<String, Object> result = serializer().subtitles(0, "https://example.com/v",
                List.of(track("en", true, "WEBVTT\n\n00:00.000 --> 00:01.000\nhi", false)));

        final Map<String, Object> only = items(result).get(0);
        assertFalse(only.containsKey("url"));
        assertEquals("WEBVTT\n\n00:00.000 --> 00:01.000\nhi", only.get("content"));
    }

    @Test
    void aStreamWithoutCaptionsHasAnEmptyList() {
        final Map<String, Object> result = serializer().subtitles(0, "https://example.com/v",
                List.of());
        assertTrue(items(result).isEmpty());
    }

    @Test
    void formatsAreChosenBySuffixAndDefaultToWebVtt() {
        assertEquals(MediaFormat.VTT, NewPipeTools.subtitleFormat(null));
        assertEquals(MediaFormat.VTT, NewPipeTools.subtitleFormat(" "));
        assertEquals(MediaFormat.TTML, NewPipeTools.subtitleFormat("TTML"));
        assertEquals(MediaFormat.TRANSCRIPT3, NewPipeTools.subtitleFormat("srv3"));
        assertEquals(List.of("vtt", "ttml", "srt", "srv1", "srv2", "srv3"),
                NewPipeTools.subtitleFormatNames());
    }

    @Test
    void mediaFormatsAreRefused() {
        final IllegalArgumentException error = assertThrows(IllegalArgumentException.class,
                () -> NewPipeTools.subtitleFormat("mp4"));
        assertTrue(error.getMessage().contains("Use one of: vtt, ttml"));
    }
}
